type Tokens = (typeof tokens)[keyof typeof tokens];

function tokenVariables(t: Tokens): Record<string, string> {
  return {
    "--x-titlebar": t.titlebar,
    "--x-tab": t.tab,
    "--x-tab-active": t.tabActive,
    "--x-bg": t.bg,
    "--x-sunken": t.sunken,
    "--x-surface": t.surface,
    "--x-card": t.card,
    "--x-card-hover": t.cardHover,
    "--x-card-action": t.cardAction,
    "--x-control": t.control,
    "--x-control-hover": t.controlHover,
    "--x-field": t.field,
    "--x-field-muted": t.fieldMuted,
    "--x-menu": t.menu,
    "--x-border": t.border,
    "--x-divider": t.divider,
    "--x-row-divider": t.rowDivider,
    "--x-text": t.text,
    "--x-text-secondary": t.textSecondary,
    "--x-text-muted": t.textMuted,
    "--x-icon-muted": t.iconMuted,
    "--x-accent": t.accent,
    "--x-accent-hover": t.accentHover,
    "--x-danger": t.danger,
    "--x-success": t.success,
    "--x-warning": t.warning,
    "--x-folder": t.folder,
    "--x-tile": t.tile,
    "--x-empty-tile-top": t.emptyTileTop,
    "--x-empty-tile-bottom": t.emptyTileBottom,
    "--x-overlay": t.overlay,
    "--x-menu-shadow": t.menuShadow,
  };
}

function schemeVariables(t: Tokens): Record<string, string> {
  return {
    ...tokenVariables(t),
    "--mantine-color-body": t.bg,
    "--mantine-color-text": t.text,
    "--mantine-color-dimmed": t.textSecondary,
    "--mantine-color-default": t.control,
    "--mantine-color-default-hover": t.controlHover,
    "--mantine-color-default-color": t.text,
    "--mantine-color-default-border": "transparent",
    "--mantine-color-error": t.danger,
    "--mantine-color-success": t.success,
    "--mantine-color-anchor": t.accent,
    "--mantine-color-placeholder": t.textSecondary,
  };
}

